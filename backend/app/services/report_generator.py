"""
CodeSentinel - Report Generator
Generates structured reports in multiple formats (JSON, Markdown).
"""

import json
from datetime import datetime, timezone
from typing import List, Dict, Any

from app.models.orm_models import Scan, Issue


class ReportGenerator:
    """Generates audit reports from scan results."""

    def generate_markdown(self, scan: Scan, issues: List[Issue]) -> str:
        """Generate a comprehensive Markdown report."""
        now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

        # Build issue sections
        security_issues = [i for i in issues if i.agent_type == "security"]
        quality_issues = [i for i in issues if i.agent_type == "quality"]
        completeness_issues = [i for i in issues if i.agent_type == "completeness"]
        dependency_issues = [i for i in issues if i.agent_type == "dependency"]

        severity_emoji = {
            "critical": "🔴",
            "high": "🟠",
            "medium": "🟡",
            "low": "🟢",
            "info": "🔵",
        }

        report = f"""# 🛡️ CodeSentinel Audit Report

**Repository:** {scan.repo_name}
**Scan Date:** {now}
**Health Score:** {scan.health_score:.0f}/100 {"🟢" if scan.health_score >= 80 else "🟡" if scan.health_score >= 50 else "🔴"}

---

## 📊 Summary

| Metric | Value |
|--------|-------|
| Total Files Scanned | {scan.total_files} |
| Total Lines of Code | {scan.total_lines:,} |
| Languages | {', '.join(scan.languages.keys()) if scan.languages else 'N/A'} |
| Total Issues | {scan.total_issues} |
| 🔴 Critical | {scan.critical_count} |
| 🟠 High | {scan.high_count} |
| 🟡 Medium | {scan.medium_count} |
| 🟢 Low | {scan.low_count} |

---

"""

        # Security section
        if security_issues:
            report += "## 🔒 Security Vulnerabilities\n\n"
            report += self._format_issues(security_issues, severity_emoji)

        # Quality section
        if quality_issues:
            report += "## 📐 Code Quality Issues\n\n"
            report += self._format_issues(quality_issues, severity_emoji)

        # Completeness section
        if completeness_issues:
            report += "## 🧩 Incomplete Implementations\n\n"
            report += self._format_issues(completeness_issues, severity_emoji)

        # Dependency section
        if dependency_issues:
            report += "## 📦 Dependency Issues\n\n"
            report += self._format_issues(dependency_issues, severity_emoji)

        # Recommendations
        report += self._generate_recommendations(issues)

        report += "\n---\n\n*Generated by CodeSentinel — AI-Powered Codebase Auditor*\n"

        return report

    def _format_issues(self, issues: List[Issue], severity_emoji: dict) -> str:
        """Format a list of issues as Markdown."""
        text = ""
        # Sort by severity
        severity_order = {"critical": 0, "high": 1, "medium": 2, "low": 3, "info": 4}
        sorted_issues = sorted(issues, key=lambda i: severity_order.get(i.severity, 4))

        for idx, issue in enumerate(sorted_issues, 1):
            emoji = severity_emoji.get(issue.severity, "⚪")
            location = ""
            if issue.file_path:
                location = f" — `{issue.file_path}`"
                if issue.line_start:
                    location += f":{issue.line_start}"

            text += f"### {emoji} {idx}. {issue.title}{location}\n\n"
            text += f"**Severity:** {issue.severity.upper()} | **Category:** {issue.category}\n\n"
            text += f"{issue.description}\n\n"

            if issue.code_snippet:
                text += f"**Code:**\n```\n{issue.code_snippet}\n```\n\n"

            if issue.explanation:
                text += f"**Why this matters:** {issue.explanation}\n\n"

            if issue.suggestion:
                text += f"**Recommended fix:** {issue.suggestion}\n\n"

            if issue.suggested_code and issue.original_code:
                text += "**Before:**\n"
                text += f"```\n{issue.original_code}\n```\n\n"
                text += "**After (suggested):**\n"
                text += f"```\n{issue.suggested_code}\n```\n\n"

            text += "---\n\n"

        return text

    def _generate_recommendations(self, issues: List[Issue]) -> str:
        """Generate prioritized recommendations based on findings."""
        text = "## 💡 Recommendations\n\n"

        critical_issues = [i for i in issues if i.severity == "critical"]
        high_issues = [i for i in issues if i.severity == "high"]

        if critical_issues:
            text += "### 🚨 Critical — Fix Immediately\n\n"
            for idx, issue in enumerate(critical_issues, 1):
                suggestion = issue.suggestion or issue.description
                text += f"{idx}. **{issue.title}** — {suggestion}\n"
            text += "\n"

        if high_issues:
            text += "### ⚠️ High Priority\n\n"
            for idx, issue in enumerate(high_issues, 1):
                suggestion = issue.suggestion or issue.description
                text += f"{idx}. **{issue.title}** — {suggestion}\n"
            text += "\n"

        # General recommendations
        categories = {i.category for i in issues}
        text += "### 📋 General\n\n"

        if "hardcoded_secret" in categories:
            text += "- **Move all secrets to environment variables** and use a secrets manager in production.\n"
        if "sql_injection" in categories:
            text += "- **Use parameterized queries** or an ORM for all database operations.\n"
        if "missing_error_handling" in categories or "bare_except" in categories:
            text += "- **Implement comprehensive error handling** with specific exception types.\n"
        if "todo_comment" in categories:
            text += "- **Resolve all TODO/FIXME comments** before deploying to production.\n"
        if "duplicate_code" in categories:
            text += "- **Refactor duplicated code** into reusable functions or modules.\n"
        if "vulnerable_dependency" in categories:
            text += "- **Update all dependencies** to their latest secure versions.\n"
        if "unpinned_dependencies" in categories:
            text += "- **Pin dependency versions** for reproducible builds.\n"

        text += "\n"
        return text

    def generate_json(self, scan: Scan, issues: List[Issue]) -> dict:
        """Generate a structured JSON report."""
        return {
            "metadata": {
                "tool": "CodeSentinel",
                "version": "1.0.0",
                "generated_at": datetime.now(timezone.utc).isoformat(),
            },
            "scan": scan.to_dict(),
            "issues": [issue.to_dict() for issue in issues],
            "summary": {
                "total_issues": len(issues),
                "by_severity": {
                    "critical": scan.critical_count,
                    "high": scan.high_count,
                    "medium": scan.medium_count,
                    "low": scan.low_count,
                    "info": scan.info_count,
                },
                "by_agent": {
                    "security": len([i for i in issues if i.agent_type == "security"]),
                    "quality": len([i for i in issues if i.agent_type == "quality"]),
                    "completeness": len([i for i in issues if i.agent_type == "completeness"]),
                    "dependency": len([i for i in issues if i.agent_type == "dependency"]),
                },
                "health_score": scan.health_score,
            },
        }


# Singleton
report_generator = ReportGenerator()
